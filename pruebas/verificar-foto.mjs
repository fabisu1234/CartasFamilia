import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const raiz = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contexto = vm.createContext({ crypto: webcrypto, TextEncoder, TextDecoder, Uint8Array, btoa, atob, window: {} });
const configuracion = await fs.readFile(path.join(raiz, 'config.js'), 'utf8');
vm.runInContext(configuracion, contexto);
const fuente = await fs.readFile(process.argv[2], 'utf8');
vm.runInContext(fuente, contexto);
const cifrador = vm.runInContext('RegaloCrypto', contexto);
const carta = await cifrador.descifrar(contexto.window.CONTENIDO_CIFRADO.papa, 'cambiar-esta-clave-papa');
assert.match(carta.foto, /^data:image\/jpeg;base64,/);
const foto = Buffer.from(carta.foto.split(',')[1], 'base64');
assert.ok(foto.length <= 300 * 1024);
assert.ok(!fuente.includes('data:image') && !fuente.includes('cambiar-esta-clave') && !fuente.includes(carta.titulo));
const prueba = path.join(raiz, 'pruebas', 'con-foto');
await fs.mkdir(prueba, { recursive: true });
for (const nombre of ['index.html', 'style.css', 'script.js', 'nieve.js']) await fs.copyFile(path.join(raiz, nombre), path.join(prueba, nombre));
await fs.writeFile(path.join(prueba, 'config.js'), configuracion.replace('const MODO_PRUEBA = false;', 'const MODO_PRUEBA = true;'));
await fs.writeFile(path.join(prueba, 'contenido-cifrado.js'), fuente);
console.log(`OK: salida del navegador descifrada; foto JPEG de ${foto.length} bytes (máximo 307200), sin contraseña, foto ni título en texto plano. Fixture preparado para comprobar DOM e imagen.`);
